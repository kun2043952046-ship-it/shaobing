#!/usr/bin/env python3
"""二进制/ASCII STL → Nav2 可用的 PGM 栅格地图（水平切片投影）

原理：按高度带 [--z-min, --z-max] 对三角面做水平切片，凡是切片落在带内的
(x, y) 栅格记为占用（0），其余为自由（254）。竖直面在 xy 上会退化成线段，
单独按线段绘制，保证薄墙不会丢。

用法：
    python3 scripts/stl2pgm.py ../models/rm_field/meshes/sk_rmmap.stl -o map
    python3 scripts/stl2pgm.py mesh.stl -o map --res 0.02 --z-min 0.05 --z-max 0.50

默认值与当前仿真一致：
    分辨率 0.02 m/px；切片高度 0.05~0.50 m（同 pointcloud_to_laserscan）；
    模型位姿 (-6.363, -4.343, 0.1)（同 models/rm_field/model.sdf）。
只依赖 numpy。
"""
import argparse
import os
import struct
import sys

import numpy as np

FREE = 254
OCCUPIED = 0


def load_stl(path):
    """读取 STL，返回 (n, 3, 3) 的顶点数组"""
    with open(path, 'rb') as f:
        data = f.read()
    if len(data) < 84:
        raise ValueError('STL 文件过短')

    n = struct.unpack('<I', data[80:84])[0]
    if 84 + 50 * n == len(data):                 # 二进制 STL
        dtype = np.dtype([('normal', '<f4', 3), ('v', '<f4', (3, 3)), ('attr', '<u2')])
        return np.frombuffer(data, dtype=dtype, count=n, offset=84)['v'].astype(np.float64)

    # ASCII STL
    verts = []
    for line in data.decode('ascii', 'ignore').splitlines():
        parts = line.split()
        if parts and parts[0] == 'vertex' and len(parts) == 4:
            verts.append([float(v) for v in parts[1:4]])
    if len(verts) % 3 != 0 or not verts:
        raise ValueError('ASCII STL 顶点解析失败')
    return np.array(verts, dtype=np.float64).reshape(-1, 3, 3)


def draw_segments(occ, tri, res, x_min, y_min, z_min, z_max):
    """竖直（在 xy 上退化）三角面：把落在高度带内的边画成 1 栅格宽的线"""
    h, w = occ.shape
    for a, b in ((0, 1), (1, 2), (2, 0)):
        p, q = tri[a], tri[b]
        if max(p[2], q[2]) < z_min or min(p[2], q[2]) > z_max:
            continue
        length = float(np.hypot(q[0] - p[0], q[1] - p[1]))
        if length <= 0.0:
            continue
        steps = max(int(length / (res * 0.5)) + 1, 2)
        s = np.linspace(0.0, 1.0, steps)
        xs = p[0] + (q[0] - p[0]) * s
        ys = p[1] + (q[1] - p[1]) * s
        zs = p[2] + (q[2] - p[2]) * s
        keep = (zs >= z_min) & (zs <= z_max)
        if not keep.any():
            continue
        ix = ((xs[keep] - x_min) / res).astype(int)
        iy = ((ys[keep] - y_min) / res).astype(int)
        ok = (ix >= 0) & (ix < w) & (iy >= 0) & (iy < h)
        occ[iy[ok], ix[ok]] = True


def rasterize(tris, res, x_min, y_min, nx, ny, z_min, z_max):
    """把高度带内的网格投影成占用栅格，返回 bool 数组 [iy, ix]"""
    occ = np.zeros((ny, nx), dtype=bool)
    step = res * 0.5
    for tri in tris:
        zs = tri[:, 2]
        if zs.max() < z_min or zs.min() > z_max:
            continue

        (x0, y0), (x1, y1), (x2, y2) = tri[0][:2], tri[1][:2], tri[2][:2]
        denom = (y1 - y2) * (x0 - x2) + (x2 - x1) * (y0 - y2)
        if abs(denom) < 1e-12:                   # xy 投影成一条线 → 竖直面
            draw_segments(occ, tri, res, x_min, y_min, z_min, z_max)
            continue

        xs = np.arange(min(x0, x1, x2), max(x0, x1, x2) + step, step)
        ys = np.arange(min(y0, y1, y2), max(y0, y1, y2) + step, step)
        if xs.size == 0 or ys.size == 0:
            continue
        gx, gy = np.meshgrid(xs, ys)

        l0 = ((y1 - y2) * (gx - x2) + (x2 - x1) * (gy - y2)) / denom
        l1 = ((y2 - y0) * (gx - x2) + (x0 - x2) * (gy - y2)) / denom
        l2 = 1.0 - l0 - l1
        inside = (l0 >= -1e-9) & (l1 >= -1e-9) & (l2 >= -1e-9)
        if not inside.any():
            continue

        gz = l0 * tri[0][2] + l1 * tri[1][2] + l2 * tri[2][2]
        hit = inside & (gz >= z_min) & (gz <= z_max)
        if not hit.any():
            continue

        ix = ((gx[hit] - x_min) / res).astype(int)
        iy = ((gy[hit] - y_min) / res).astype(int)
        ok = (ix >= 0) & (ix < nx) & (iy >= 0) & (iy < ny)
        occ[iy[ok], ix[ok]] = True
    return occ


def write_pgm(path, img):
    h, w = img.shape
    with open(path, 'wb') as f:
        f.write(b'P5\n')
        f.write(b'# generated by stl2pgm.py\n')
        f.write(b'%d %d\n255\n' % (w, h))
        f.write(img.tobytes())


def main():
    ap = argparse.ArgumentParser(description='STL → PGM 栅格地图')
    ap.add_argument('stl', help='STL 文件路径')
    ap.add_argument('-o', '--output', default='map', help='输出前缀（生成 <前缀>.pgm/.yaml）')
    ap.add_argument('--res', type=float, default=0.02, help='分辨率 m/px，默认 0.02')
    ap.add_argument('--z-min', type=float, default=0.05, help='切片下限高度（世界系），默认 0.05')
    ap.add_argument('--z-max', type=float, default=0.50, help='切片上限高度（世界系），默认 0.50')
    ap.add_argument('--pose', type=float, nargs=3, default=[-6.363, -4.343, 0.0],
                    metavar=('X', 'Y', 'Z'), help='模型位姿平移，默认 -6.363 -4.343 0.0')
    ap.add_argument('--margin', type=float, default=0.0, help='地图四周额外留边（米）')
    args = ap.parse_args()

    tris = load_stl(args.stl) + np.asarray(args.pose, dtype=np.float64)

    x_min = float(tris[:, :, 0].min()) - args.margin
    y_min = float(tris[:, :, 1].min()) - args.margin
    x_max = float(tris[:, :, 0].max()) + args.margin
    y_max = float(tris[:, :, 1].max()) + args.margin
    nx = int(round((x_max - x_min) / args.res))
    ny = int(round((y_max - y_min) / args.res))

    occ = rasterize(tris, args.res, x_min, y_min, nx, ny, args.z_min, args.z_max)

    img = np.full((ny, nx), FREE, dtype=np.uint8)
    img[occ] = OCCUPIED
    write_pgm(args.output + '.pgm', np.flipud(img))   # PGM 第 0 行 = y 最大

    with open(args.output + '.yaml', 'w') as f:
        f.write(f'image: {os.path.basename(args.output)}.pgm\n')
        f.write(f'resolution: {args.res}\n')
        f.write(f'origin: [{x_min:.3f}, {y_min:.3f}, 0.0]\n')
        f.write('negate: 0\n')
        f.write('occupied_thresh: 0.65\n')
        f.write('free_thresh: 0.25\n')

    print(f'{args.stl} -> {args.output}.pgm / {args.output}.yaml')
    print(f'  三角面 {len(tris)}，切片带 z {args.z_min}~{args.z_max} m')
    print(f'  地图 {nx} x {ny} px，分辨率 {args.res} m/px')
    print(f'  覆盖 x {x_min:.3f}~{x_max:.3f} / y {y_min:.3f}~{y_max:.3f} m')
    print(f'  占用栅格 {int(occ.sum())}（{100.0 * occ.sum() / occ.size:.1f}%）')
    return 0


if __name__ == '__main__':
    sys.exit(main())
